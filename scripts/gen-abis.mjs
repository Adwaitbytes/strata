// Generates packages/sdk/src/abis.ts from Foundry build output. Run after `forge build`.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const out = "packages/contracts/out";
const contracts = [
  ["strataArenaAbi", "IStrataArena.sol/IStrataArena.json"],
  ["scoreAttestorAbi", "IScoreAttestor.sol/IScoreAttestor.json"],
  ["rewardsDistributorAbi", "RewardsDistributor.sol/RewardsDistributor.json"],
];
let src = "// GENERATED by scripts/gen-abis.mjs from Foundry output. Do not edit by hand.\n\n";
for (const [name, path] of contracts) {
  const p = join(out, path);
  if (!existsSync(p)) continue;
  const abi = JSON.parse(readFileSync(p, "utf8")).abi;
  src += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync("packages/sdk/src/abis.ts", src);
console.log("wrote packages/sdk/src/abis.ts");
