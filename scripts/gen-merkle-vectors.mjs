// Generates golden merkle vectors for the ScoreAttestor forge tests from the TypeScript reference
// implementation (packages/sdk/src/merkle.ts), so Solidity and TS are proven to agree (D20).
// Usage (repo root): pnpm --filter @strata/sdk build && node scripts/gen-merkle-vectors.mjs
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";
import { encodeLeaf, buildTree, verifyProof } from "../packages/sdk/dist/merkle.js";

const OUT = "packages/contracts/test/generated/MerkleGoldenVectors.sol";

// Fixed fixture values. Covers zero and max-ish fields, negative PnL, and an odd leaf count
// (the last node is promoted unchanged, which exercises unequal proof lengths).
const leaves = [
  { season: 1n, epoch: 7n, agentId: 1n, score: 9_120n, spreadCentiBps: 1_250n, depthUsd: 48_000n, uptimeBps: 9_990n, pnlUsdCents: 12_345n, flags: 0n },
  { season: 1n, epoch: 7n, agentId: 2n, score: 7_800n, spreadCentiBps: 2_200n, depthUsd: 30_500n, uptimeBps: 9_500n, pnlUsdCents: -98_765n, flags: 1n },
  { season: 1n, epoch: 7n, agentId: 3n, score: 0n, spreadCentiBps: 0n, depthUsd: 0n, uptimeBps: 0n, pnlUsdCents: 0n, flags: 0n },
  { season: 1n, epoch: 7n, agentId: 4n, score: 10_000n, spreadCentiBps: 99n, depthUsd: 1_000_000n, uptimeBps: 10_000n, pnlUsdCents: -1n, flags: 6n },
  { season: 1n, epoch: 7n, agentId: 5n, score: 5_555n, spreadCentiBps: 4_321n, depthUsd: 12_345n, uptimeBps: 8_000n, pnlUsdCents: 2n ** 200n, flags: 2n ** 255n },
];

const hashes = leaves.map(encodeLeaf);
const tree = buildTree(hashes);
hashes.forEach((h, i) => {
  if (!verifyProof(h, tree.proofs[i], tree.root)) throw new Error(`TS self-check failed for leaf ${i}`);
});
const single = buildTree([hashes[0]]);

const lit = (v) => (v < 0n ? `-${(-v).toString()}` : v.toString());
const field = (l) =>
  `ScoreLeaf({season: ${l.season}, epoch: ${l.epoch}, agentId: ${l.agentId}, score: ${l.score}, spreadCentiBps: ${l.spreadCentiBps}, depthUsd: ${l.depthUsd}, uptimeBps: ${l.uptimeBps}, pnlUsdCents: ${lit(l.pnlUsdCents)}, flags: ${l.flags}})`;

let body = "";
body += `    uint256 internal constant COUNT = ${leaves.length};\n`;
body += `    bytes32 internal constant ROOT = ${tree.root};\n`;
body += `    bytes32 internal constant SINGLE_ROOT = ${single.root};\n\n`;
body += `    function leaf(uint256 i) internal pure returns (ScoreLeaf memory) {\n`;
leaves.forEach((l, i) => {
  body += `        if (i == ${i}) return ${field(l)};\n`;
});
body += `        revert("index");\n    }\n\n`;
body += `    function leafHash(uint256 i) internal pure returns (bytes32) {\n`;
hashes.forEach((h, i) => {
  body += `        if (i == ${i}) return ${h};\n`;
});
body += `        revert("index");\n    }\n\n`;
body += `    function proof(uint256 i) internal pure returns (bytes32[] memory p) {\n`;
tree.proofs.forEach((pr, i) => {
  body += `        if (i == ${i}) {\n            p = new bytes32[](${pr.length});\n`;
  pr.forEach((x, j) => {
    body += `            p[${j}] = ${x};\n`;
  });
  body += `            return p;\n        }\n`;
});
body += `        revert("index");\n    }\n`;

const src = `// SPDX-License-Identifier: MIT
pragma solidity 0.8.28;

// GENERATED by scripts/gen-merkle-vectors.mjs from packages/sdk/src/merkle.ts. Do not edit by hand.

struct ScoreLeaf {
    uint64 season;
    uint64 epoch;
    uint256 agentId;
    uint256 score;
    uint256 spreadCentiBps;
    uint256 depthUsd;
    uint256 uptimeBps;
    int256 pnlUsdCents;
    uint256 flags;
}

library MerkleGoldenVectors {
${body}}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, src);
console.log(`wrote ${OUT} (root ${tree.root})`);
